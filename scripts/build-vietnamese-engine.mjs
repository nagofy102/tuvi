// Reproducible integration of the pinned MIT engine; never mutate node_modules.
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const pkg = JSON.parse(readFileSync('node_modules/iztro/package.json', 'utf8'));
if (pkg.version !== '2.6.2') throw new Error('Review the bridge before upgrading iztro.');
const check = process.argv.includes('--check');
const output = 'src/domain/astrology/vendor/iztro-vietnam.cjs';
const result = await build({
  stdin: { contents: "export { astro } from 'iztro';", resolveDir: process.cwd() },
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  outfile: output,
  write: !check,
  packages: 'external',
  plugins: [
    {
      name: 'vietnamese-calendar-seam',
      setup(builder) {
        builder.onResolve({ filter: /^iztro$/ }, () => ({
          path: resolve('node_modules/iztro/lib/index.js'),
        }));
        builder.onResolve({ filter: /^lunar-lite$/ }, () => ({
          path: resolve('src/domain/calendar/engine-bridge.ts'),
        }));
        // Keep the Vietnamese converter and its validation in the generated artifact.
        builder.onResolve({ filter: /^@dqcai\/vn-lunar$/ }, () => ({
          // The require entry is CommonJS incorrectly labeled type:module.
          path: resolve('node_modules/@dqcai/vn-lunar/lib/index.mjs'),
        }));
      },
    },
  ],
  banner: {
    js: `/* Generated by npm run engine:build. Do not edit.\n${readFileSync('node_modules/iztro/LICENSE', 'utf8')}\n${readFileSync('src/domain/astrology/vendor/NOTICE.md', 'utf8')}\n*/`,
  },
});
if (check && result.outputFiles[0].text !== readFileSync(output, 'utf8')) {
  throw new Error('Stale engine artifact. Run npm run engine:build and review the diff.');
}
